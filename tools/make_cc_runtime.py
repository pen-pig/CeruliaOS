"""Package cc's fixed-address runtime from ELF, without external host libraries."""
import pathlib
import struct
import sys


def main():
    src, dest = map(pathlib.Path, sys.argv[1:])
    elf = src.read_bytes()
    if elf[:7] != b'\x7fELF\x01\x01\x01':
        raise ValueError('expected a little-endian ELF32 runtime')
    phoff = struct.unpack_from('<I', elf, 28)[0]
    entsize, count = struct.unpack_from('<HH', elf, 42)
    blob = None
    for i in range(count):
        kind, off, va, _, size, _, _, _ = struct.unpack_from(
            '<8I', elf, phoff + i * entsize)
        if kind == 1 and va == 0x400000:
            blob = elf[off:off + size]
    if not blob or len(blob) > 4096:
        raise ValueError('missing runtime text segment')
    if blob[5] != 0xe8 or any(blob[32 + 5 * i] != 0xe9 for i in range(8)):
        raise ValueError('runtime entry or jump table no longer matches cc')
    lines = ['/* Generated by tools/make_cc_runtime.py. */',
             'static const unsigned char cc_runtime[] = {']
    for i in range(0, len(blob), 16):
        lines.append('    ' + ','.join(str(b) for b in blob[i:i + 16]) + ',')
    lines += ['};', 'static const char *const runtime_names[] = {',
              '    "puts", "putchar", "printf", "write", "read", "open", "close", "exit"',
              '};']
    dest.write_text('\n'.join(lines) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
